# Задача 1. Підрахунок островів на карті M x N (1 - суша, 0 - океан).
# Острів - це клітинки суші, з'єднані по горизонталі або по вертикалі.
# По діагоналі клітинки не з'єднуються, так виходить у прикладах із завдання.
# Йдемо по матриці, на кожній новій суші запускаємо обхід у глибину (DFS) і
# обнуляємо всі клітинки цього острова. Час роботи O(M * N), рекурсії немає.


def count_islands(matrix):
    # Відвідану сушу обнуляємо прямо в matrix, щоб не витрачати зайву пам'ять.
    # Через це після виклику вхідна матриця змінюється
    m = len(matrix)
    n = len(matrix[0]) if m else 0
    islands = 0

    for i in range(m):
        for j in range(n):

            # Якщо знайшли сушу, починаємо новий острів
            if matrix[i][j] == 1:
                islands += 1

                # Стек зберігає координати клітинок, які ще треба обійти
                stack = [(i, j)]
                matrix[i][j] = 0

                while stack:
                    x, y = stack.pop()

                    # Перевіряємо сусідів: вниз, вгору, праворуч, ліворуч
                    neighbors = [
                        (x + 1, y),
                        (x - 1, y),
                        (x, y + 1),
                        (x, y - 1)
                    ]

                    for nx, ny in neighbors:
                        if (
                            0 <= nx < m
                            and 0 <= ny < n
                            and matrix[nx][ny] == 1
                        ):
                            matrix[nx][ny] = 0
                            stack.append((nx, ny))

    return islands


if __name__ == "__main__":
    # 1. Вводимо розміри матриці: M і N в одному рядку
    m, n = map(int, input().split())

    # 2. Вводимо матрицю: M рядків по N чисел
    matrix = [list(map(int, input().split())) for _ in range(m)]

    # 3. Рахуємо острови й виводимо результат
    print(count_islands(matrix))
